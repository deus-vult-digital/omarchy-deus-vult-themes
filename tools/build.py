#!/usr/bin/env python3
"""Build the Deus Vult Omarchy themes, one for each phosphor of phosphors.toml.

Each becomes a complete theme folder, build/deus-vult-<phosphor>/, the way its
own repo (omarchy-deus-vult-<phosphor>-theme) carries it:

    colors.toml, btop.theme, icons.theme    from phosphors.toml
    backgrounds/, unlock.png                tools/make-backgrounds.py
    assets/banner.png                       the Deus Vult banner generator, in the phosphor
    preview-unlock.png                      tools/make-preview-unlock.sh
    preview.png                             tools/stage-preview.sh (needs a Wayland session)
    README.md, LICENSE

and a small copy of its preview goes to assets/previews/ for this repo's
README. tools/publish.sh pushes the folders to their repos.

    tools/build.py                          # all four, everything
    tools/build.py amber-monochrome         # one
    tools/build.py --quick paper-white      # no videos, no staged preview

The banner comes from deusvult-site's brand/banner/make-banner.py: set
MAKE_BANNER to it, or keep deusvult-site checked out beside this repo.
"""

import argparse
import importlib.util
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools"
PUBLIC = "https://github.com/deus-vult-digital"  # where the theme repos are mirrored for installing
DATA = tomllib.loads((ROOT / "phosphors.toml").read_text(encoding="utf-8"))
ANSI, PHOSPHORS = DATA["ansi"], DATA["phosphor"]
VIDEOS = ("4-live-cross", "intro-1-cross", "intro-2-every-square-pixel", "intro-3-boot")


def slug(key: str) -> str:
    return f"deus-vult-{key}"


def repo(key: str) -> str:
    return f"omarchy-deus-vult-{key}-theme"


def install_url(key: str) -> str:
    return f"{PUBLIC}/{repo(key)}.git"


def rgba(hex_colour: str, alpha: str) -> str:
    return f"rgba({hex_colour.lstrip('#')}{alpha})"


def colors_toml(key: str) -> str:
    p = PHOSPHORS[key]
    r, fld = p["ramp"], p["field"]
    lines = [
        f'# Deus Vult {p["name"]}: {p["code"]} {p["colour"]} phosphor on a dark CRT field (deusvult.digital).',
        f"# Background, foreground, accent and borders are the {p['code']} ramp. The ANSI",
        "# colours are the same in every Deus Vult phosphor (the site's other phosphors",
        "# and a plain red), so errors, warnings and diffs still read as what they are.",
        "# Generated by tools/build.py from phosphors.toml.",
        "",
        'mode = "dark"',
        "",
        f'accent = "{r[1]}"',
        f'selection = "{r[5]}"',
        f'muted = "{p["muted"]}"',
        "",
        f'background = "{fld[1]}"',
        f'dark_background = "{fld[2]}"',
        f'darker_background = "{fld[3]}"',
        f'lighter_background = "{fld[0]}"',
        "",
        f'foreground = "{p["light"]}"',
        f'dark_foreground = "{r[3]}"',
        f'light_foreground = "{p["pale"]}"',
        f'bright_foreground = "{p["palest"]}"',
        "",
        f'hyprland_active_border = "{rgba(r[0], "ee")} {rgba(r[3], "ee")} 45deg"',
        f'hyprland_inactive_border = "{rgba(r[5], "aa")}"',
        "",
    ]
    for group in ("", "bright_"):
        names = ["red", "yellow", "orange", "green", "cyan", "blue", "magenta", "brown"]
        lines += [f'{group}{n} = "{ANSI[group + n]}"' for n in names if group + n in ANSI]
        lines.append("")
    return "\n".join(lines[:-1]) + "\n"


def btop_theme(key: str) -> str:
    p = PHOSPHORS[key]
    r, fld = p["ramp"], p["field"]
    bright, primary, _, muted, dim, deep = r
    pale = p["pale"]
    rows = [
        ("main_bg", fld[1]), ("main_fg", p["light"]), ("title", bright), ("hi_fg", primary),
        ("selected_bg", deep), ("selected_fg", p["palest"]), ("inactive_fg", p["muted"]), ("graph_text", pale),
        ("meter_bg", fld[0]), ("proc_misc", bright), None,
        ("cpu_box", dim), ("mem_box", dim), ("net_box", dim), ("proc_box", dim), ("div_line", deep), None,
        ("temp_start", primary), ("temp_mid", ANSI["yellow"]), ("temp_end", ANSI["red"]), None,
        ("cpu_start", muted), ("cpu_mid", primary), ("cpu_end", pale), None,
        ("free_start", deep), ("free_mid", muted), ("free_end", primary), None,
        ("cached_start", muted), ("cached_mid", primary), ("cached_end", bright), None,
        ("available_start", primary), ("available_mid", ANSI["yellow"]), ("available_end", ANSI["orange"]), None,
        ("used_start", primary), ("used_mid", bright), ("used_end", pale), None,
        ("download_start", muted), ("download_mid", primary), ("download_end", bright), None,
        ("upload_start", muted), ("upload_mid", primary), ("upload_end", bright), None,
        ("process_start", muted), ("process_mid", primary), ("process_end", pale), None,
        *((f"gradient_color_{i}", c) for i, c in enumerate([fld[1], fld[0], deep, dim, muted, primary, bright, pale])),
    ]
    out = [
        f"# Deus Vult {p['name']}: btop on a {p['code']} phosphor CRT. Boxes and graphs run the",
        f"# {p['colour']} ramp; temperature and the \"available\" meter climb into amber and red.",
        "# Generated by tools/build.py from phosphors.toml.",
        "",
    ]
    out += ["" if row is None else f'theme[{row[0]}]="{row[1]}"' for row in rows]
    return "\n".join(out) + "\n"


def palette_rows(key: str) -> str:
    p = PHOSPHORS[key]
    r = p["ramp"]
    rows = [
        ("background", p["field"][1], "black with a tint of the phosphor"),
        ("foreground", p["light"], "pale phosphor"),
        ("accent", r[1], f"{p['code']} {p['colour']}"),
        ("bright", r[0], "window borders, titles"),
        ("selection", r[5], ""),
        ("muted", p["muted"], "comments, hints"),
        ("red", ANSI["red"], "errors stay red"),
        ("yellow", ANSI["yellow"], "P3 amber"),
        ("orange", ANSI["orange"], ""),
        ("green", ANSI["green"], "P1 green"),
        ("blue", ANSI["blue"], "P11 blue"),
        ("cyan", ANSI["cyan"], ""),
        ("magenta", ANSI["magenta"], ""),
    ]
    return "\n".join(f"| {role} | `{c}` | {note} |" for role, c, note in rows)


def others(key: str) -> str:
    return "\n".join(
        f"- **{q['name']}** ({q['code']} {q['colour']}): `omarchy theme install {install_url(k)}`"
        for k, q in PHOSPHORS.items() if k != key
    )


def readme(key: str) -> str:
    p = PHOSPHORS[key]
    template = Template((ROOT / "templates" / "README.md").read_text(encoding="utf-8"))
    return template.substitute(
        name=p["name"], code=p["code"], colour=p["colour"], slug=slug(key), install=install_url(key),
        icons=p["icons"], palette=palette_rows(key), others=others(key),
    )


def make_banner(key: str, dest: Path) -> None:
    """The Deus Vult README banner, drawn in green, then recoloured to the phosphor."""
    tool = Path(os.environ.get("MAKE_BANNER") or ROOT.parent / "deusvult-site/brand/banner/make-banner.py")
    if not tool.is_file():
        sys.exit(f"build: no banner generator at {tool}; set MAKE_BANNER")
    p = PHOSPHORS[key]
    svg = dest / "assets" / "banner.svg"
    svg.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [sys.executable, str(tool), "--title", "Deus Vult", "--command", f"omarchy theme set {slug(key)}",
         "--tagline", f"{p['name']} · a {p['code']} phosphor theme for Omarchy",
         "--footer", "OMARCHY 4.5 · THEME · MIT", "-o", str(svg)],
        check=True, stdout=subprocess.DEVNULL,
    )
    # make-banner.py draws only in P1 green on its green field.
    swap = {"#22c55e": p["ramp"][1], "#0b1a10": p["field"][0], "#050b07": p["field"][1], "#010201": p["field"][3]}
    text = svg.read_text(encoding="utf-8")
    for old, new in swap.items():
        text = text.replace(old, new)
    svg.write_text(text, encoding="utf-8")
    png = subprocess.run(["rsvg-convert", str(svg)], check=True, capture_output=True).stdout
    subprocess.run(["magick", "-", "-strip", str(dest / "assets" / "banner.png")], input=png, check=True)
    svg.unlink()


def build(key: str, quick: bool) -> None:
    dest = ROOT / "build" / slug(key)
    print(f"build: {dest}")
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    (dest / "colors.toml").write_text(colors_toml(key), encoding="utf-8")
    (dest / "btop.theme").write_text(btop_theme(key), encoding="utf-8")
    (dest / "icons.theme").write_text(PHOSPHORS[key]["icons"] + "\n", encoding="utf-8")
    (dest / "README.md").write_text(readme(key), encoding="utf-8")
    shutil.copy(ROOT / "LICENSE", dest / "LICENSE")

    spec = importlib.util.spec_from_file_location("make_backgrounds", TOOLS / "make-backgrounds.py")
    backgrounds = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(backgrounds)
    only = [t for t in backgrounds.TARGETS if t not in VIDEOS] if quick else None
    backgrounds.make(key, dest, only)

    make_banner(key, dest)
    subprocess.run([str(TOOLS / "make-preview-unlock.sh"), str(dest)], check=True)
    if not quick:
        subprocess.run([str(TOOLS / "stage-preview.sh"), str(dest)], check=True,
                       env={**os.environ, "ANSI": PHOSPHORS[key]["ansi"]})
        small = ROOT / "assets" / "previews" / f"{slug(key)}.png"
        small.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["magick", str(dest / "preview.png"), "-resize", "1280x720", "-strip", str(small)], check=True)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("phosphor", nargs="*", help=f"any of {', '.join(PHOSPHORS)}; default all")
    p.add_argument("--quick", action="store_true", help="skip the videos and the staged preview.png")
    a = p.parse_args()
    for key in a.phosphor:
        if key not in PHOSPHORS:
            p.error(f"no phosphor {key!r} in phosphors.toml")
    for key in a.phosphor or PHOSPHORS:
        build(key, a.quick)


if __name__ == "__main__":
    main()
